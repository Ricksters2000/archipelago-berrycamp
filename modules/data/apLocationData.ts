// Location IDs from: https://github.com/PoryGoneDev/Celeste-Archipelago-Open-World/blob/main/Source/Locations/APLocationData.cs

export type LocationType = SimpleLocationType | NumberIdLocationType | BinocularsLocationType;
export type SimpleLocationType = `car` | `golden` | `cassette` | `heart` | `gem` | `checkpoint` | `levelClear` | `room`;
type NumberIdLocationType = `berry` | `key`
type BinocularsLocationType = `binoculars`

type LocationTuple = [chapter: number, side: number, room: string];
type NumberIdLocationTuple = [chapter: number, side: number, room: string, id: number];
type StringIdLocationTuple = [chapter: number, side: number, room: string, id: string];

export type LocationData = NumberIdLocationData | BinocularsLocationData | {
  type: SimpleLocationType;
  location: LocationTuple;
}

type NumberIdLocationData = {
  type: NumberIdLocationType;
  location: NumberIdLocationTuple;
}

type BinocularsLocationData = {
  type: BinocularsLocationType;
  location: StringIdLocationTuple;
}

export const getLocationDataFromAP = (ap: number) => {
  let locationData: LocationData | undefined;
  if (CheckpointAPToID[ap]) {
    locationData = CheckpointAPToID[ap];
  } else if (LevelClearAPToID[ap]) {
    locationData = LevelClearAPToID[ap];
  } else if (CassetteAPToID[ap]) {
    locationData = CassetteAPToID[ap];
  } else if (CrystalHeartAPToID[ap]) {
    locationData = CrystalHeartAPToID[ap];
  } else if (KeyAPToID[ap]) {
    locationData = KeyAPToID[ap];
  } else if (GemAPToID[ap]) {
    locationData = GemAPToID[ap];
  } else if (CarAPToID[ap]) {
    locationData = CarAPToID[ap];
  } else if (StrawberryAPToID[ap]) {
    locationData = StrawberryAPToID[ap];
  } else if (BinocularsAPToID[ap]) {
    locationData = BinocularsAPToID[ap];
  } else if (RoomAPToID[ap]) {
    locationData = RoomAPToID[ap];
  }
  if (!locationData) {
    console.error(`Failed to find location data from archipelago ID: ${ap}`);
    locationData = {type: `berry`, location: [0, 0, `missing-${ap}`, -1]}
  }
  return locationData;
}

