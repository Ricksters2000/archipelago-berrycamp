type SingleItemType = keyof Omit<PlayerInventory, MultipleItemType | MultipleRoomItemType>
type MultipleItemType = `checkpoints`
type MultipleRoomItemType = `keys` | `gems`

export type ItemData = SingleItemData | MultipleItemData | MultipleRoomItemData;

type SingleItemData = {type: SingleItemType}

type MultipleItemData = {
  type: MultipleItemType;
  chapterId: number;
  chapterName: string;
  sideId: SideId;
  roomId: string;
}

type MultipleRoomItemData = Omit<MultipleItemData, `type`> & {
  type: MultipleRoomItemType;
  itemId: number;
  itemName: string;
}

